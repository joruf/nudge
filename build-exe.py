#!/usr/bin/env python3
"""Build Nudge as a single executable file.

One command, the same on every platform - run it on the system the file is
meant for, because PyInstaller cannot build for another one:

    ./build-exe.py              Linux   -> dist/nudge-linux-x86_64-<version>-build<build>
    py build-exe.py             Windows -> dist/nudge-windows-x86_64-<version>-build<build>.exe

What it does:

1. creates a private build environment in ``build/exe/venv`` (without the
   system's site packages, so nothing the build machine happens to have ends up
   in the file),
2. installs PyInstaller and, on Linux, python-xlib, which gives the idle
   measurement and some techniques their precise X11 path,
3. writes a small entry script and the PyInstaller spec,
4. runs PyInstaller and checks that the result starts (``--version``).

The version is the one in ``nudge/__init__.py``; it is raised by hand and never
derived from anything.

Not in the file: ``evdev`` and ``dbus-python`` (Linux only, they need compiled
system libraries).  Without them the key/mouse activity and the screensaver
state are not seen - the same degradation a source checkout shows when they are
missing.  The installer window of ``python -m nudge`` is also not part of the
executable: nothing can be installed into a single file.

Options:

    --clean          rebuild the build environment from scratch
    --keep-env       reuse the build environment without updating its packages
    --print-version  print "<version> <build>" and exit (used by the workflow)

Author:  Joachim Ruf, Loresoft.de
"""

from __future__ import annotations

import argparse
import platform
import shutil
import subprocess
import sys
import venv
from pathlib import Path
from typing import List

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))

from nudge import VERSION_LABEL, __build__, __version__  # noqa: E402

APP_ID = "nudge"
IS_WINDOWS = sys.platform.startswith("win")
IS_LINUX = sys.platform.startswith("linux")

BUILD_DIR = ROOT / "build" / "exe"
VENV_DIR = BUILD_DIR / "venv"
WORK_DIR = BUILD_DIR / "work"
SPEC_FILE = WORK_DIR / "nudge.spec"
ENTRY_FILE = WORK_DIR / "entry.py"
ICON_FILE = WORK_DIR / "nudge.ico"
DIST_DIR = ROOT / "dist"

#: The same PyInstaller generation the other projects build with.
PYINSTALLER_SPEC = "pyinstaller>=6.9"

#: Optional pure-Python packages that are carried when the platform has them.
LINUX_PACKAGES = ["python-xlib"]

#: The program's own packages.  Imported normally, but collected completely so
#: nothing depends on PyInstaller seeing every import (the techniques are
#: loaded by name).
PROGRAM_PACKAGES = ["nudge"]

#: Third-party packages whose submodules are collected completely.
LINUX_COLLECT = ["Xlib"]

#: Data files, relative to the project root: (source, folder inside the file).
DATA_FILES = [
    (Path("nudge") / "locales", "nudge/locales"),
    (Path("Nudge.desktop"), "."),
]

ENTRY_TEMPLATE = '''# Generated by build-exe.py - edit that script, not this file.
"""Entry point of the single-file executable.

Not ``python -m nudge``: the installer window that module opens installs system
packages, which cannot work inside a single file.
"""
import os
import sys


def use_system_library_path() -> None:
    """Give child programs (xdotool, ...) the library path of the system.

    PyInstaller points LD_LIBRARY_PATH at the unpacked files; a child program
    that inherits it loads the bundled libraries instead of its own.  The
    already running process keeps what it has loaded.
    """
    if not sys.platform.startswith("linux"):
        return
    original = os.environ.get("LD_LIBRARY_PATH_ORIG")
    if original is None:
        os.environ.pop("LD_LIBRARY_PATH", None)
    else:
        os.environ["LD_LIBRARY_PATH"] = original


if getattr(sys, "frozen", False):
    use_system_library_path()

if sys.argv[1:] == ["--version"]:
    # The start test of build-exe.py: what the window needs must be inside the file, and a
    # missing tkinter would otherwise only show once somebody opens the window.
    import tkinter  # noqa: F401, E402

from nudge.__main__ import main  # noqa: E402

sys.exit(main())
'''

SPEC_TEMPLATE = '''# Generated by build-exe.py - edit that script, not this file.
from PyInstaller.utils.hooks import collect_submodules

datas = {datas!r}
binaries = []
hiddenimports = []
for package in {collect!r}:
    hiddenimports += collect_submodules(package)

a = Analysis(
    [{entry!r}],
    pathex=[{root!r}],
    binaries=binaries,
    datas=datas,
    hiddenimports=hiddenimports,
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[],
    excludes=[],
    noarchive=False,
)
pyz = PYZ(a.pure)
exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.datas,
    [],
    name={name!r},
    debug=False,
    strip=False,
    upx=False,
    runtime_tmpdir=None,
    # A desktop program: no console window on Windows.
    console=False,
    icon={icon!r},
)
'''


def info(message: str) -> None:
    """Print a progress line."""
    print("[build-exe] " + message, flush=True)


def fail(message: str) -> None:
    """Print an error and stop with exit code 1."""
    print("[build-exe] ERROR: " + message, file=sys.stderr, flush=True)
    sys.exit(1)


def executable_name(version: str = "", build: object = "") -> str:
    """Return the file name of the executable for this platform and version.

    :param version: ``major.minor.patch``; defaults to the program's.
    :param build: The build number; defaults to the program's.
    :return: e.g. ``nudge-linux-x86_64-1.2.0-build3`` or
        ``nudge-windows-x86_64-1.2.0-build3.exe``.
    """
    version = version or __version__
    build = build or __build__
    machine = platform.machine().lower()
    machine = {"amd64": "x86_64", "x64": "x86_64", "arm64": "aarch64"}.get(machine, machine)
    system = "windows" if IS_WINDOWS else "linux"
    return "{0}-{1}-{2}-{3}-build{4}{5}".format(
        APP_ID, system, machine, version, build, ".exe" if IS_WINDOWS else "")


def venv_python() -> Path:
    """Return the interpreter of the build environment."""
    if IS_WINDOWS:
        return VENV_DIR / "Scripts" / "python.exe"
    return VENV_DIR / "bin" / "python"


def run(command: List[object], **kwargs) -> None:
    """Run a command and stop the build when it fails."""
    info("$ " + " ".join(str(part) for part in command))
    completed = subprocess.run([str(part) for part in command], **kwargs)
    if completed.returncode != 0:
        fail("command failed with exit code {0}".format(completed.returncode))


def check_build_host() -> None:
    """Stop early when this machine cannot produce a complete program."""
    if not (IS_LINUX or IS_WINDOWS):
        fail("Nudge runs on Linux and Windows; build on one of them.")
    if sys.version_info < (3, 10):
        fail("building needs Python 3.10 or newer.")
    try:
        import tkinter  # noqa: F401
    except ImportError:
        fail("tkinter is missing - Linux: sudo apt install python3-tk")


def bundled_packages() -> List[str]:
    """Return the pip packages to install into the build environment."""
    packages = [PYINSTALLER_SPEC]
    if IS_LINUX:
        packages.extend(LINUX_PACKAGES)
    return packages


def prepare_venv(clean: bool, keep: bool) -> None:
    """Create or refresh the build environment."""
    if clean and VENV_DIR.exists():
        info("Removing the old build environment ...")
        shutil.rmtree(str(VENV_DIR))
    if not venv_python().exists():
        info("Creating the build environment in {0} ...".format(VENV_DIR))
        venv.EnvBuilder(with_pip=True).create(str(VENV_DIR))
    elif keep:
        info("Reusing the build environment as it is.")
        return
    run([venv_python(), "-m", "pip", "install", "--upgrade", "--disable-pip-version-check", "pip"])
    run([venv_python(), "-m", "pip", "install", "--upgrade", "--disable-pip-version-check"]
        + bundled_packages())


def windows_icon() -> "Path | None":
    """Render the program's own icon as an .ico for the Windows file."""
    if not IS_WINDOWS:
        return None
    from nudge.ui.window_icon import render_icon_ico

    ICON_FILE.write_bytes(render_icon_ico())
    return ICON_FILE


def spec_text() -> str:
    """Return the PyInstaller spec file for this platform."""
    name = executable_name()
    if name.endswith(".exe"):
        name = name[:-4]
    collect = list(PROGRAM_PACKAGES) + (LINUX_COLLECT if IS_LINUX else [])
    icon = windows_icon()
    return SPEC_TEMPLATE.format(
        datas=[(str(ROOT / source), target) for source, target in DATA_FILES],
        collect=collect,
        entry=str(ENTRY_FILE),
        root=str(ROOT),
        name=name,
        icon=str(icon) if icon else None,
    )


def smoke_test(executable: Path) -> None:
    """Start the result once and make sure it answers."""
    info("Starting {0} --version ...".format(executable.name))
    completed = subprocess.run([str(executable), "--version"], stdout=subprocess.PIPE,
                               stderr=subprocess.STDOUT, timeout=300)
    output = completed.stdout.decode("utf-8", errors="replace").strip()
    if completed.returncode != 0:
        fail("the executable did not start (exit code {0}):\n{1}".format(completed.returncode, output))
    # A windowed Windows build has no stdout to print to; the exit code has to do.
    if output and VERSION_LABEL not in output:
        fail("the executable reports {0!r}, expected {1}".format(output, VERSION_LABEL))
    info("OK: " + (output or "exit code 0"))


def main() -> int:
    """Run the whole build."""
    parser = argparse.ArgumentParser(description="Build Nudge as a single executable file.")
    parser.add_argument("--clean", action="store_true", help="rebuild the build environment from scratch")
    parser.add_argument("--keep-env", action="store_true",
                        help="reuse the build environment without updating its packages")
    parser.add_argument("--print-version", action="store_true",
                        help='print "<version> <build>" and exit')
    args = parser.parse_args()

    if args.print_version:
        print("{0} {1}".format(__version__, __build__))
        return 0

    check_build_host()
    info("Nudge {0} for {1}".format(VERSION_LABEL, executable_name()))
    prepare_venv(clean=args.clean, keep=args.keep_env)
    WORK_DIR.mkdir(parents=True, exist_ok=True)
    ENTRY_FILE.write_text(ENTRY_TEMPLATE, encoding="utf-8")
    SPEC_FILE.write_text(spec_text(), encoding="utf-8")
    run([venv_python(), "-m", "PyInstaller", "--noconfirm", "--clean",
         "--distpath", DIST_DIR, "--workpath", WORK_DIR, SPEC_FILE], cwd=str(ROOT))

    result = DIST_DIR / executable_name()
    if not result.is_file():
        fail("PyInstaller finished but {0} is missing".format(result))
    smoke_test(result)
    info("Done: {0} ({1:.1f} MB)".format(result, result.stat().st_size / 1048576))
    info("This file runs on {0} only; build on the other system for its own file.".format(
        "Windows" if IS_WINDOWS else "Linux"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
